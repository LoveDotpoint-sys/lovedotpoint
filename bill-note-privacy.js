/* Love Dot Point POS - Bill Note Privacy
   Special order notes stay visible to waiter/owner live operations,
   but never appear on customer bill preview, final receipt, print or reprint.
*/
(function(){
  'use strict';

  // Current bill / final receipt: render item name only, never the internal note.
  window.billItemRows=function(){
    return (items||[]).map((i,idx)=>`<tr><td class="sr">${idx+1}</td><td class="itemname">${i.item_name}</td><td class="num">${i.qty}</td><td class="num">${Number(i.unit_price).toFixed(2)}</td><td class="num">${(Number(i.unit_price)*i.qty).toFixed(2)}</td></tr>`).join('');
  };

  // Historical bill/reprint is generated by existing report code.
  // Remove only item-note <small> elements inside the receipt bill table.
  const oldViewHistoricBill=window.viewHistoricBill;
  if(typeof oldViewHistoricBill==='function'){
    window.viewHistoricBill=async function(sessionId){
      await oldViewHistoricBill(sessionId);
      const receipt=document.getElementById('receiptPrint');
      if(!receipt)return;
      receipt.querySelectorAll('.bill-table tbody td small').forEach(el=>el.remove());
    };
  }

  // Safety layer: before any print, strip bill-table notes if a legacy receipt is open.
  function stripReceiptNotes(){
    const receipt=document.getElementById('receiptPrint');
    if(receipt)receipt.querySelectorAll('.bill-table tbody td small').forEach(el=>el.remove());
  }
  window.addEventListener('beforeprint',stripReceiptNotes);
})();